export function zipCodeToCounty(zipCode: string): string | null {
  const normalized = zipCode.replace(/\D/g, ""); // Remove non-digits

  if (normalized.length !== 5) {
    return null;
  }

  return zipToCountyMap[normalized] || null;
}

export function isValidBayAreaZip(zipCode: string): boolean {
  return zipCodeToCounty(zipCode) !== null;
}
